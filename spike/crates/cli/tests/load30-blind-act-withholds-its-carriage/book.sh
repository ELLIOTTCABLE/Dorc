# TARGET (`30P:law-no-unsoundness-below-a-blind-act`, the nothing-shipped clause): a book that
# moves the working directory to somewhere Dorc cannot name, then sources its own sibling package
# RELATIVELY. The operand is a plain literal and the controller reads the file, so the AUTHOR named
# the target — but which file that operand resolves to on the host is now unknown, and a copy of a
# file Dorc cannot prove the author's own line will read is engine selection.
#
# So: the `.` line survives verbatim (no re-point, no paste), the package's bytes are carried by no
# form, and the reader is told which line above cost them the dependency. The `hork tune` site
# below binds nothing from the package either — cwd-⊤ costs the load its authority as well as its
# carriage — so it runs.
cd "$SITE_ROOT"

. ./hork.dorc.sh

hork tune web
